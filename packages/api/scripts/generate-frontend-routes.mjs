/**
 * Builds types/generated-routes-frontend.ts from .mercur/_generated/index.ts by replacing
 * typeof import("../../src/api/...") with a local stub so admin/vendor tsc does not
 * compile packages/api/src/api/** under strict settings.
 *
 * Run after: bunx @mercurjs/cli@latest codegen
 */
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const srcPath = join(root, ".mercur", "_generated", "index.ts")
const outPath = join(root, "types", "generated-routes-frontend.ts")

let text = readFileSync(srcPath, "utf8")
text = text.replace(
  /typeof import\("(\.\.\/\.\.\/src\/api\/[^"]+)"\)/g,
  (full, relPath) => {
    // Keep real modules for admin requests so @mercurjs/client infers query/mutation I/O in admin.
    if (relPath.includes("/admin/requests/")) {
      return full
    }
    return 'typeof import("./mercur-custom-route-stub")'
  },
)

const banner = `// Generated by scripts/generate-frontend-routes.mjs — do not edit by hand.
// Source: .mercur/_generated/index.ts (Mercur CLI). Re-run this script after codegen.

/// <reference path="./mercur-core-plugin-shims.d.ts" />

`

if (text.includes("This file is generated automatically by Mercur CLI")) {
  text = text.replace(
    /\/\/ This file is generated automatically by Mercur CLI\n\/\/ Do not edit this file manually\n\n/,
    "",
  )
}

// index.ts lives under .mercur/_generated (two levels below packages/api); this file is under types/
text = text.replace(/\.\.\/\.\.\/src\/api\//g, "../src/api/")

writeFileSync(outPath, banner + text, "utf8")
console.log("Wrote", outPath)
